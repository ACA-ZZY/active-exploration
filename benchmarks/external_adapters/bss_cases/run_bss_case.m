function report = run_bss_case(case_slug, output_dir, random_seed, hf_budget, cpu_core, replay_journal_source)
%RUN_BSS_CASE Run one project case with native BSS and a strict HF ceiling.
%
% This entry keeps the authors' sequential SUR/GP/SMC/MH computation and uses
% the separately versioned lazy-oracle instrumentation so an HF call is made
% only after SUR has selected a point.  No project reference probability or
% reference threshold is constructed or passed to BSS.

expected_commit = '574e083634b9d640c4e6bdfc6b94f923e074ff82';
case_slug = char(string(case_slug));
output_dir = char(string(output_dir));
random_seed = double(random_seed);
hf_budget = double(hf_budget);
cpu_core = double(cpu_core);
if nargin < 6, replay_journal_source = ''; end
replay_journal_source = char(string(replay_journal_source));
replay_mode = ~isempty(replay_journal_source);
assert(isscalar(random_seed) && isfinite(random_seed) && random_seed >= 0 ...
    && random_seed <= 2^32 - 1 && random_seed == floor(random_seed), ...
    'random_seed must be a uint32-compatible integer.');
assert(isscalar(hf_budget) && isfinite(hf_budget) && hf_budget > 0 ...
    && hf_budget == floor(hf_budget), 'hf_budget must be a positive integer.');
assert(isscalar(cpu_core) && isfinite(cpu_core) && cpu_core >= 0 ...
    && cpu_core == floor(cpu_core), 'cpu_core must be a non-negative integer.');
if ~isfolder(output_dir), mkdir(output_dir); end
oracle_journal_path = fullfile(output_dir, 'oracle_journal.jsonl');
if replay_mode
    assert(isfile(replay_journal_source), 'Replay oracle journal is absent.');
    if isfile(oracle_journal_path)
        assert(strcmp(fileread(oracle_journal_path), fileread(replay_journal_source)), ...
            'Existing recovery journal differs from its declared replay source.');
    else
        [copied, message] = copyfile(replay_journal_source, oracle_journal_path);
        assert(copied, 'Cannot copy replay oracle journal: %s', message);
    end
else
    assert(~isfile(oracle_journal_path), 'BSS:ExistingOracleJournal', ...
        ['Refusing to append to an existing oracle journal because a rerun could ' ...
         'repeat true-physics calls.']);
end

adapter_root = fileparts(mfilename('fullpath'));
external_root = fileparts(adapter_root);
moretest_root = fileparts(external_root);
budgeted_root = fullfile(external_root, 'bss_budgeted');
bss_root = fullfile(moretest_root, 'third_party', 'bss');
setup_bss_paths(bss_root, budgeted_root, expected_commit);

oracle_x = zeros(0, 0);
oracle_g = zeros(0, 1);
oracle_score = zeros(0, 1);
hf_count = 0;
budget_gate_hits = 0;
oracle_request_count = 0;
oracle_journal_sequence = 0;
[replay_callbacks, replay_total_rows] = load_replay_journal( ...
    replay_journal_source, case_slug, replay_mode);
replay_cursor = 0;
new_physical_rows_this_invocation = 0;
[problem, case_contract] = bss_project_problem(case_slug, @counted_score);
initial_data = load(fullfile(output_dir, 'initial_training.mat'));
initial_design_size = size(initial_data.x0, 1);
assert(hf_budget >= initial_design_size, ...
    'BSS:BudgetTooSmall', 'Budget must cover the shared initial design.');

options = bss_get_default_options([], problem);
options.N0 = initial_design_size;
options.figs.disable_all = true;
assert(options.use_gp && options.N0 == initial_design_size, ...
    'Native BSS initial-design contract drift.');
assert(options.samplesize == 1000 && options.p0 == 0.1, ...
    'Native BSS N/p0 contract drift.');
assert(options.SUR.max_eval_per_stage == 100, ...
    'Native BSS SUR contract drift.');
native_stopping_threshold = options.stopping_thresh;
options.stopping_thresh = @budgeted_stopping_threshold;

rng(random_seed, 'twister');
started = tic;
try
    x0 = initial_data.x0;
    y0 = counted_score(x0);
    assert(size(x0, 1) == initial_design_size && hf_count == initial_design_size, ...
        'Initial HF ledger drift.');
    stage_data = bss_lazy_oracle(problem, options, x0, y0);
catch cause
    elapsed_seconds = toc(started);
    save_partial_failure(cause, elapsed_seconds);
    rethrow(cause);
end
elapsed_seconds = toc(started);

if replay_mode
    assert(replay_cursor == numel(replay_callbacks), ...
        'Replay completed after %d/%d saved oracle callbacks.', ...
        replay_cursor, numel(replay_callbacks));
    assert(hf_count == replay_total_rows, 'Replay/journal HF total mismatch.');
end

stopped_by_hf_budget_cap = (budget_gate_hits > 0) || (hf_count >= hf_budget);
native_converged = ~stopped_by_hf_budget_cap;
if stopped_by_hf_budget_cap
    termination_reason = 'hf_budget_cap';
else
    termination_reason = 'native_stopping_rule';
end

stage_evaluations = [stage_data.n_evals];
expected_hf = initial_design_size + sum(stage_evaluations);
assert(hf_count == expected_hf, 'BSS:HFLedgerDrift', ...
    'Expected %d HF rows from BSS decisions, observed %d.', expected_hf, hf_count);
assert(hf_count <= hf_budget, 'BSS:BudgetExceeded', ...
    'HF budget exceeded: %d > %d.', hf_count, hf_budget);
assert(size(unique(oracle_x, 'rows'), 1) == hf_count, ...
    'BSS:DuplicateOraclePoint', 'BSS oracle points must be unique.');

cursor = initial_design_size;
for stage = 1:numel(stage_data)
    count = stage_data(stage).n_evals;
    selected = oracle_x(cursor + (1:count), :);
    stage_selected = double(stage_data(stage).selected_x);
    assert(isequal(size(selected), size(stage_selected)) ...
        && isequaln(selected, stage_selected), ...
        'BSS:SelectionLedgerDrift', 'Selected-point log mismatch at stage %d.', stage);
    cursor = cursor + count;
end
assert(cursor == hf_count, 'HF cursor mismatch.');

stage_rows = make_stage_rows(stage_data);
ledger = make_ledger(stage_data, initial_design_size, hf_count, hf_budget);
options_contract = struct( ...
    'use_gp', options.use_gp, ...
    'samplesize', options.samplesize, ...
    'p0', options.p0, ...
    'N0', options.N0, ...
    'sur_min_eval_per_stage', options.SUR.min_eval_per_stage, ...
    'sur_max_eval_per_stage', options.SUR.max_eval_per_stage, ...
    'mh_steps', options.MH.nb_steps, ...
    'mh_adapt', options.MH.do_adapt, ...
    'mh_target_rate', options.MH.target_rate);
result_path = fullfile(output_dir, 'result.mat');
temporary_result = [result_path '.tmp.mat'];
save(temporary_result, 'stage_data', 'oracle_x', 'oracle_g', 'oracle_score', ...
    'x0', 'y0', 'options_contract', 'case_contract', 'random_seed', ...
    'hf_budget', '-v7');
movefile(temporary_result, result_path, 'f');
write_json_atomic(fullfile(output_dir, 'ledger.json'), ledger);

report = struct( ...
    'schema', 'bss-project-run-v1', ...
    'status', 'complete', ...
    'method', 'BSS author implementation, lazy-oracle instrumentation', ...
    'case', case_slug, ...
    'dimension', problem.dim, ...
    'random_seed', random_seed, ...
    'random_generator', 'twister', ...
    'requested_cpu_core', cpu_core, ...
    'recovery_mode', replay_mode, ...
    'new_physical_rows_this_invocation', new_physical_rows_this_invocation, ...
    'replayed_physical_rows', double(replay_mode) * hf_count, ...
    'declared_event', 'g <= 0', ...
    'bss_internal_score', '-g', ...
    'bss_internal_excursion', '-g > 0', ...
    'continuous_boundary_probability', 0.0, ...
    'reference_probability_supplied', false, ...
    'reference_threshold_supplied', false, ...
    'native_initial_design_size', initial_design_size, ...
    'native_population', options.samplesize, ...
    'native_conditional_probability', options.p0, ...
    'native_sur_max_evaluations_per_stage', options.SUR.max_eval_per_stage, ...
    'hf_budget', hf_budget, ...
    'hf_physical_rows', hf_count, ...
    'hf_remaining', hf_budget - hf_count, ...
    'budget_gate_hits', budget_gate_hits, ...
    'completed_before_budget_cap', native_converged, ...
    'native_converged', native_converged, ...
    'stopped_by_hf_budget_cap', stopped_by_hf_budget_cap, ...
    'termination_reason', termination_reason, ...
    'number_of_stages', numel(stage_data), ...
    'stage_new_evaluations', stage_evaluations, ...
    'pf_estimate', stage_data(end).Pf, ...
    'stage_results', stage_rows, ...
    'ledger', ledger, ...
    'elapsed_seconds', elapsed_seconds, ...
    'third_party_repository', 'https://git.code.sf.net/p/kriging/contrib-bss', ...
    'third_party_commit', expected_commit, ...
    'third_party_api', 'functions/bss/bss.m', ...
    'instrumented_api', 'external_adapters/bss_budgeted/bss_lazy_oracle.m', ...
    'instrumentation_diff', 'external_adapters/bss_budgeted/AUTHOR_LAZY_ORACLE.diff', ...
    'python_physics_source', case_contract.python_physics_source, ...
    'result_artifact', 'result.mat', ...
    'ledger_artifact', 'ledger.json', ...
    'oracle_journal_artifact', 'oracle_journal.jsonl', ...
    'matlab_version', version, ...
    'matlab_release', version('-release'), ...
    'stk_version', stk_version());
write_json_atomic(fullfile(output_dir, 'summary.json'), report);
fprintf('BSS_PROJECT_RESULT=%s\n', jsonencode(report));

    function score = counted_score(x)
        x = double(x);
        rows = size(x, 1);
        if hf_count + rows > hf_budget
            error('BSS:BudgetExceeded', ...
                'Oracle request of %d rows would exceed budget %d/%d.', ...
                rows, hf_count, hf_budget);
        end
        if replay_mode
            replay_cursor = replay_cursor + 1;
            assert(replay_cursor <= numel(replay_callbacks), ...
                'Algorithm requested more oracle callbacks than the saved journal.');
            saved = replay_callbacks(replay_cursor);
            assert(isequal(size(x), size(saved.x)) && isequaln(x, saved.x), ...
                'BSS:ReplayInputDrift', ...
                'Replay input mismatch at callback %d (%s).', ...
                replay_cursor, saved.request_id);
            response = saved.g;
            score = saved.score;
        else
            oracle_request_count = oracle_request_count + 1;
            request_id = sprintf('oracle-%06d', oracle_request_count);
            oracle_journal_sequence = oracle_journal_sequence + 1;
            append_oracle_event(struct( ...
                'schema', 'bss-oracle-journal-event-v1', ...
                'sequence', oracle_journal_sequence, ...
                'event', 'request_started', ...
                'request_id', request_id, ...
                'physical_rows', rows, ...
                'cumulative_returned_rows', hf_count, ...
                'x', x));
            response = bss_project_response(case_slug, x);
            score = -response;
            oracle_journal_sequence = oracle_journal_sequence + 1;
            append_oracle_event(struct( ...
                'schema', 'bss-oracle-journal-event-v1', ...
                'sequence', oracle_journal_sequence, ...
                'event', 'response_returned', ...
                'request_id', request_id, ...
                'physical_rows', rows, ...
                'cumulative_returned_rows', hf_count + rows, ...
                'x', x, ...
                'g', response, ...
                'score', score));
            new_physical_rows_this_invocation = ...
                new_physical_rows_this_invocation + rows;
        end
        if isempty(oracle_x)
            oracle_x = zeros(0, size(x, 2));
        end
        oracle_x = [oracle_x; x];
        oracle_g = [oracle_g; response];
        oracle_score = [oracle_score; score];
        hf_count = hf_count + rows;
    end

    function append_oracle_event(event)
        % Close after every record so a hard-kill preserves all prior
        % returned rows.  An unmatched request_started event is explicitly
        % treated by the Python launcher as an unknown in-flight HF call.
        file_id = fopen(oracle_journal_path, 'a');
        assert(file_id >= 0, 'Cannot append %s', oracle_journal_path);
        cleanup = onCleanup(@() fclose(file_id));
        written = fprintf(file_id, '%s\n', jsonencode(event));
        assert(written > 0, 'Cannot append oracle event to %s', oracle_journal_path);
        clear cleanup;
    end

    function threshold = budgeted_stopping_threshold(stage, final_stage, squared_cov)
        threshold = native_stopping_threshold(stage, final_stage, squared_cov);
        if hf_count >= hf_budget
            threshold = Inf;
            budget_gate_hits = budget_gate_hits + 1;
        end
    end

    function save_partial_failure(cause, seconds)
        partial_path = fullfile(output_dir, 'partial_failure.mat');
        save(partial_path, 'oracle_x', 'oracle_g', 'oracle_score', ...
            'random_seed', 'hf_budget', '-v7');
        failure = struct( ...
            'schema', 'bss-project-failure-v1', ...
            'status', 'failed', ...
            'case', case_slug, ...
            'random_seed', random_seed, ...
            'hf_budget', hf_budget, ...
            'hf_physical_rows_before_failure', hf_count, ...
            'recovery_mode', replay_mode, ...
            'new_physical_rows_this_invocation', new_physical_rows_this_invocation, ...
            'oracle_journal_artifact', 'oracle_journal.jsonl', ...
            'identifier', cause.identifier, ...
            'message', cause.message, ...
            'elapsed_seconds', seconds, ...
            'automatic_resume_allowed', false);
        write_json_atomic(fullfile(output_dir, 'failure.json'), failure);
    end
end

function setup_bss_paths(bss_root, budgeted_root, expected_commit)
assert(isfolder(bss_root), 'Pinned BSS checkout is absent: %s', bss_root);
[status, output] = system(sprintf('git -C "%s" rev-parse HEAD', bss_root));
assert(status == 0 && strcmp(strtrim(output), expected_commit), ...
    'Pinned BSS commit mismatch.');
[dirty_status, ~] = system(sprintf('git -C "%s" diff --quiet', bss_root));
assert(dirty_status == 0, 'Pinned BSS tracked source is dirty.');
addpath(budgeted_root);
addpath(fullfile(bss_root, 'scripts'));
addpath(fullfile(bss_root, 'examples'));
addpath(fullfile(bss_root, 'functions'));
addpath(fullfile(bss_root, 'functions', 'distrib'));
addpath(fullfile(bss_root, 'functions', 'bss'));
addpath(fullfile(bss_root, 'stk'));
stk_init;
mex_path = fullfile(bss_root, 'functions', 'bss', ['replicate_particles.' mexext]);
assert(isfile(mex_path), 'Compiled BSS helper is absent: %s', mex_path);
end

function rows = make_stage_rows(stage_data)
rows = repmat(struct('stage', 0, 'u_base', 0, 'u_target', 0, ...
    'pf_estimate', 0, 'estimated_squared_cov', 0, 'new_hf_rows', 0, ...
    'acceptance_expected', [], 'acceptance_observed', [], 'proposal_scale', []), ...
    numel(stage_data), 1);
for stage = 1:numel(stage_data)
    rows(stage).stage = stage;
    rows(stage).u_base = stage_data(stage).u_base;
    rows(stage).u_target = stage_data(stage).u_target;
    rows(stage).pf_estimate = stage_data(stage).Pf;
    rows(stage).estimated_squared_cov = stage_data(stage).squaredCoV;
    rows(stage).new_hf_rows = stage_data(stage).n_evals;
    if isfield(stage_data, 'accept_rate') && ~isempty(stage_data(stage).accept_rate)
        rows(stage).acceptance_expected = stage_data(stage).accept_rate.expected;
        rows(stage).acceptance_observed = stage_data(stage).accept_rate.observed;
    end
    if isfield(stage_data, 'sig_RW') && ~isempty(stage_data(stage).sig_RW)
        rows(stage).proposal_scale = stage_data(stage).sig_RW;
    end
end
end

function ledger = make_ledger(stage_data, initial_size, total, budget)
events = repmat(struct('event_id', '', 'role', '', 'stage', 0, ...
    'physical_rows', 0, 'cumulative_physical_rows', 0, 'artifact', 'result.mat'), ...
    numel(stage_data) + 1, 1);
events(1) = struct('event_id', 'initial-design', 'role', 'design', 'stage', 0, ...
    'physical_rows', initial_size, 'cumulative_physical_rows', initial_size, ...
    'artifact', 'result.mat');
cumulative = initial_size;
for stage = 1:numel(stage_data)
    count = stage_data(stage).n_evals;
    cumulative = cumulative + count;
    events(stage + 1) = struct( ...
        'event_id', sprintf('stage-%03d-sur', stage), ...
        'role', 'sequential-SUR', ...
        'stage', stage, ...
        'physical_rows', count, ...
        'cumulative_physical_rows', cumulative, ...
        'artifact', 'result.mat');
end
assert(cumulative == total, 'Ledger total mismatch.');
ledger = struct( ...
    'schema', 'bss-hf-ledger-v1', ...
    'counting_rule', 'Every true response row evaluated by the lazy oracle, from zero.', ...
    'initial_shared_data_reused', false, ...
    'budget', budget, ...
    'events', events, ...
    'totals', struct('physical_rows', total, 'remaining', budget - total));
end

function [callbacks, total_rows] = load_replay_journal(path, case_slug, enabled)
callbacks = struct('request_id', {}, 'x', {}, 'g', {}, 'score', {});
total_rows = 0;
if ~enabled, return; end
switch char(string(case_slug))
    case {'two-sided-kink', 'cantilever_beam_2d'}
        dimension = 2;
    case 'radial-kink'
        dimension = 8;
    case 'tail-kink'
        dimension = 50;
    otherwise
        error('Unsupported replay case: %s', case_slug);
end
lines = splitlines(string(fileread(path)));
expected_sequence = 1;
pending = [];
for index = 1:numel(lines)
    if strlength(strtrim(lines(index))) == 0, continue; end
    event = jsondecode(char(lines(index)));
    assert(strcmp(event.schema, 'bss-oracle-journal-event-v1'), ...
        'Unknown replay journal schema at line %d.', index);
    assert(event.sequence == expected_sequence, ...
        'Replay journal sequence drift at line %d.', index);
    expected_sequence = expected_sequence + 1;
    rows = double(event.physical_rows);
    assert(isscalar(rows) && rows > 0 && rows == floor(rows), ...
        'Invalid replay row count at line %d.', index);
    values = reshape(double(event.x), rows, dimension);
    assert(all(isfinite(values), 'all'), ...
        'Nonfinite replay input at line %d.', index);
    if strcmp(event.event, 'request_started')
        assert(isempty(pending), ...
            'Overlapping oracle requests in replay journal at line %d.', index);
        assert(event.cumulative_returned_rows == total_rows, ...
            'Replay request cumulative count drift at line %d.', index);
        pending = struct('request_id', event.request_id, ...
            'physical_rows', rows, 'x', values);
    elseif strcmp(event.event, 'response_returned')
        assert(~isempty(pending), ...
            'Replay response lacks a request at line %d.', index);
        assert(strcmp(event.request_id, pending.request_id) ...
            && rows == pending.physical_rows ...
            && isequaln(values, pending.x), ...
            'Replay request/response mismatch at line %d.', index);
        response = reshape(double(event.g), rows, 1);
        score = reshape(double(event.score), rows, 1);
        assert(all(isfinite(response), 'all') && all(isfinite(score), 'all') ...
            && isequaln(score, -response), ...
            'Invalid replay response at line %d.', index);
        total_rows = total_rows + rows;
        assert(event.cumulative_returned_rows == total_rows, ...
            'Replay response cumulative count drift at line %d.', index);
        callbacks(end + 1) = struct( ...
            'request_id', char(string(event.request_id)), ...
            'x', values, 'g', response, 'score', score); %#ok<AGROW>
        pending = [];
    else
        error('Unknown replay journal event at line %d.', index);
    end
end
assert(isempty(pending), ...
    'Replay journal ends with an unknown in-flight physical request.');
assert(~isempty(callbacks), 'Replay journal contains no returned oracle call.');
end

function write_json_atomic(path, value)
path = char(string(path));
parent = fileparts(path);
if ~isempty(parent) && ~isfolder(parent), mkdir(parent); end
temporary = [path '.tmp'];
file_id = fopen(temporary, 'w');
assert(file_id >= 0, 'Cannot write %s', temporary);
cleanup = onCleanup(@() fclose(file_id));
fprintf(file_id, '%s\n', jsonencode(value, PrettyPrint=true));
clear cleanup;
movefile(temporary, path, 'f');
end
