function [problem, contract] = bss_project_problem(case_slug, cost_fun)
%BSS_PROJECT_PROBLEM Build a native BSS problem without reference leakage.
%
% The authors' implementation estimates an upper excursion f > u_final.
% We therefore expose f=-g and u_final=0.  Under the continuous Gaussian
% inputs this is probability-equivalent to the declared project event g<=0;
% the boundary g=0 has probability zero.

case_slug = char(string(case_slug));
if nargin < 2 || isempty(cost_fun)
    cost_fun = @(x) -bss_project_response(case_slug, x);
end

switch case_slug
    case 'two-sided-kink'
        dim = 2;
        source = 'cases/two-sided-kink/problem.py';
    case 'radial-kink'
        dim = 8;
        source = 'cases/radial-kink/problem.py';
    case 'tail-kink'
        dim = 50;
        source = 'cases/tail-kink/problem.py';
    case 'cantilever_beam_2d'
        dim = 2;
        source = 'cases/cantilever_beam_2d/problem.py';
    otherwise
        error('BSS:UnknownCase', 'Unknown BSS project case: %s', case_slug);
end

input_distrib = NormalDistribution(zeros(1, dim), ones(1, dim));
problem = struct( ...
    'name', case_slug, ...
    'dim', dim, ...
    'cost_fun', cost_fun, ...
    'input_distrib', input_distrib, ...
    'u_final', 0.0, ...
    'LSS_expr', 'project event g(x) <= 0; BSS score -g(x) > 0');

contract = struct( ...
    'case', case_slug, ...
    'dimension', dim, ...
    'latent_distribution', 'independent standard normal', ...
    'declared_event', 'g <= 0', ...
    'bss_score', '-g', ...
    'bss_excursion', '-g > 0', ...
    'boundary_note', 'P(g=0)=0 under the continuous input law', ...
    'python_physics_source', source, ...
    'contains_reference_probability', false, ...
    'contains_reference_threshold', false);
end
